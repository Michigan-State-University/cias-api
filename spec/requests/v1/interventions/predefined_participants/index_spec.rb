# frozen_string_literal: true

require 'rails_helper'

RSpec.describe 'GET /v1/interventions/:intervention_id/predefined_participants', type: :request do
  context 'with an intervention with predefined participants' do
    let!(:intervention) { create(:intervention, :with_predefined_participants, user: researcher) }
    let(:researcher) { create(:user, :researcher, :confirmed) }
    let(:current_user) { researcher }
    let(:request) do
      get v1_intervention_predefined_participants_path(intervention_id: intervention.id), headers: current_user.create_new_auth_token
    end

    it 'return correct status' do
      request
      expect(response).to have_http_status(:ok)
    end

    it 'return correct body' do
      request
      expect(json_response['data'].size).to eql(intervention.predefined_users.size)
    end

    it 'the element from array has correct keys' do
      request
      expect(json_response['data'].first['attributes'].keys).to match_array(%w[full_name first_name last_name phone slug health_clinic_id auto_invitation
                                                                               sms_invitation_sent_at email external_id active email_autogenerated
                                                                               sms_notification email_notification email_invitation_sent_at
                                                                               ra_session_completed ra_session_finished_at ra_session_fulfilled_by_email
                                                                               first_opened_at last_reminder_sent_at])
    end

    it_behaves_like 'users without access'
  end

  describe 'query count' do
    include PredefinedParticipantSmsHelpers

    let(:researcher) { create(:user, :researcher, :confirmed) }
    let(:headers) { researcher.create_new_auth_token }
    let(:opened_at) { Time.zone.local(2026, 11, 2, 9, 30, 0) }

    def intervention_with_participants(count)
      intervention = create(:intervention, :published, user: researcher)
      create_list(:user, count, :predefined_participant, :confirmed, :with_phone).each do |user|
        user.predefined_user_parameter.update!(intervention_id: intervention.id)
        user.predefined_user_parameter.update_columns(first_opened_at: opened_at, last_reminder_sent_at: opened_at + 3.days)
      end
      intervention
    end

    def index_queries_for(intervention)
      get v1_intervention_predefined_participants_path(intervention_id: intervention.id), headers: headers
      count_queries do
        get v1_intervention_predefined_participants_path(intervention_id: intervention.id), headers: headers
      end
    end

    it 'serves the new fields for every participant' do
      intervention = intervention_with_participants(5)

      get v1_intervention_predefined_participants_path(intervention_id: intervention.id), headers: headers

      attributes = json_response['data'].pluck('attributes')
      expect(attributes.size).to eq(5)
      expect(attributes).to all(include('first_opened_at', 'last_reminder_sent_at'))
      expect(attributes.pluck('first_opened_at')).to all(be_present)
    end

    it 'runs the same number of queries for 5 participants as for 1' do
      queries_for_one = index_queries_for(intervention_with_participants(1))
      queries_for_five = index_queries_for(intervention_with_participants(5))

      expect(queries_for_five).to eq(queries_for_one)
    end
  end
end
