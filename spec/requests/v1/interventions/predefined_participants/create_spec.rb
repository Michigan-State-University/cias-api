# frozen_string_literal: true

require 'rails_helper'

RSpec.describe 'POST /v1/interventions/:intervention_id/predefined_participants', type: :request do
  let(:request) do
    post v1_intervention_predefined_participants_path(intervention_id: intervention.id), params: params, headers: current_user.create_new_auth_token
  end
  let!(:intervention) { create(:intervention, user: researcher) }
  let(:researcher) { create(:user, :researcher, :confirmed) }
  let(:current_user) { researcher }
  let(:params) do
    {
      predefined_user: {
        first_name: Faker::Name.first_name,
        last_name: Faker::Name.last_name
      }
    }
  end

  it 'return correct status' do
    request
    expect(response).to have_http_status(:created)
  end

  it 'return correct body' do
    request
    expect(json_response['data']['attributes'].keys).to match_array(%w[full_name first_name last_name phone slug health_clinic_id auto_invitation
                                                                       sms_invitation_sent_at email external_id active email_autogenerated sms_notification
                                                                       email_notification email_invitation_sent_at])
  end

  it_behaves_like 'users without access'

  context 'with nested phone attributes' do
    let(:params) do
      {
        predefined_user: {
          first_name: 'John',
          last_name: 'Doe',
          external_id: 'ext-1',
          sms_notification: true,
          phone_attributes: { iso: 'US', prefix: '+1', number: '2025550123' }
        }
      }
    end
    let(:created_user) { intervention.reload.predefined_users.first }

    before { request }

    it 'persists phone' do
      expect(created_user.phone.slice(:iso, :prefix, :number)).to eq('iso' => 'US', 'prefix' => '+1', 'number' => '2025550123')
    end

    it 'persists predefined user parameters' do
      expect(created_user.predefined_user_parameter.slice(:external_id, :sms_notification)).to eq('external_id' => 'ext-1',
                                                                                                  'sms_notification' => true)
    end
  end

  context 'when predefined_user key is missing' do
    let(:params) { { first_name: 'John' } }

    before { request }

    it { expect(response).to have_http_status(:bad_request) }
  end

  context 'when predefined_user contains only unpermitted attributes' do
    let(:params) { { predefined_user: { roles: %w[admin] } } }

    before { request }

    it { expect(response).to have_http_status(:bad_request) }
  end
end
