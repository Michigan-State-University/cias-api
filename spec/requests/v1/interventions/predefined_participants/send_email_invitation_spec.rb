# frozen_string_literal: true

require 'rails_helper'

RSpec.describe 'POST /v1/interventions/:intervention_id/predefined_participants/:id/sms_email_invitation', type: :request do
  let!(:intervention) { create(:intervention, :with_predefined_participants, user: researcher) }
  let(:researcher) { create(:user, :researcher, :confirmed) }
  let(:user) { intervention.predefined_users.first }
  let(:user_id) { user.id }
  let(:current_user) { researcher }
  let(:request) do
    post send_email_invitation_v1_intervention_predefined_participant_path(intervention_id: intervention.id, id: user_id),
         headers: current_user.create_new_auth_token
  end

  it 'return correct body' do
    request
    expect(json_response['email_invitation_sent_at']).to be_nil
  end

  context 'when user has assigned phone' do
    before do
      user.update(email_autogenerated: false)
    end

    it 'return correct status' do
      request
      expect(response).to have_http_status(:ok)
    end

    it 'return correct body' do
      request
      expect(json_response['email_invitation_sent_at']).to be_present
    end
  end

  context 'when id is wrong' do
    let(:user_id) { 'wrongId' }

    it 'return correct status' do
      request
      expect(response).to have_http_status(:not_found)
    end
  end

  it_behaves_like 'users without access'

  describe 'authentication and current editor gate' do
    include PredefinedParticipantSmsHelpers

    let(:researcher) { create(:user, :researcher, :confirmed) }
    let(:current_user) { researcher }
    let!(:intervention) { create(:intervention, :published, user: researcher) }
    let!(:pup) { make_participant(intervention, index: 0, invited_at: Time.zone.parse('2026-10-20 09:00:00')) }
    let(:participant_id) { pup.user.id }
    let(:base) { "/v1/interventions/#{intervention.id}/predefined_participants/#{participant_id}" }
    let(:email_path) { "#{base}/send_email_invitation" }
    let(:provider_fails) { false }
    let(:collaborator) { create(:user, :researcher, :confirmed) }
    let(:request) { post email_path, headers: current_user.create_new_auth_token }

    before do
      stub_const('ENV', ENV.to_hash.merge('WEB_URL' => 'https://web.example.test'))
      allow_any_instance_of(Communication::Sms).to receive(:send_message).and_return(true) unless provider_fails
    end

    it 'answers 401 without a token' do
      post email_path
      expect(response).to have_http_status(:unauthorized)
    end

    it_behaves_like 'users without access'

    context 'with a collaborator who has edit: true' do
      before do
        pup.user.update_columns(email_autogenerated: false)
        create(:collaborator, intervention: intervention, user: collaborator, edit: true, view: true)
      end

      it 'answers 403 when the collaborator is not the current editor' do
        intervention.update!(current_editor: researcher)
        post email_path, headers: collaborator.create_new_auth_token
        expect(response).to have_http_status(:forbidden)
      end

      it 'sends no e-mail for the non-editor' do
        intervention.update!(current_editor: researcher)
        expect { post email_path, headers: collaborator.create_new_auth_token }.not_to(change { ActionMailer::Base.deliveries.size })
      end

      it 'does not stamp email_invitation_sent_at for the non-editor' do
        intervention.update!(current_editor: researcher)
        expect { post email_path, headers: collaborator.create_new_auth_token }.not_to(change { pup.reload.email_invitation_sent_at })
      end

      it 'the same collaborator gets 200 and the e-mail goes out once they are the current editor' do
        intervention.update!(current_editor: collaborator)
        expect { post email_path, headers: collaborator.create_new_auth_token }.to(change { ActionMailer::Base.deliveries.size }.by(1))
        expect(response).to have_http_status(:ok)
      end
    end
  end
end
