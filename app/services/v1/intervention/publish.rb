# frozen_string_literal: true

class V1::Intervention::Publish
  def initialize(intervention)
    @intervention = intervention
    @sessions = intervention.sessions.order(:position)
  end

  def execute
    timestamp_published_at
    calculate_days_after_schedule
    delete_preview_data
    send_smses_to_predefined_users
    set_autoclose_for_sessions
  end

  private

  attr_accessor :intervention
  attr_reader :sessions

  def timestamp_published_at
    intervention.update!(published_at: Time.current)
  end

  def calculate_days_after_schedule
    schedule_time = DateTime.current
    sessions.each do |session|
      next if session.schedule == 'after_fill'

      if session.schedule == 'exact_date'
        schedule_time = session.schedule_at
        next
      end

      schedule_time += selected_number_of_days(session)
      next if %w[days_after_fill days_after_date].include?(session.schedule)

      if session.schedule == 'days_after'
        session.schedule_at = schedule_time.to_s
        session.save!
      end
    end
  end

  def delete_preview_data
    session_ids = intervention.sessions.select(:id)
    preview_users = User.where(preview_session_id: session_ids)
    preview_user_ids = preview_users.select(:id)
    UserIntervention.where(user_id: preview_user_ids).destroy_all
    UserLogRequest.where(user_id: preview_user_ids).destroy_all
    preview_users.destroy_all
  end

  def selected_number_of_days(session)
    return 0 if session.schedule_payload.blank?

    session.schedule_payload.days
  end

  def send_smses_to_predefined_users
    predefined_user_parameters.where(auto_invitation: true).includes(user: :phone).find_in_batches do |batch|
      opted_out_user_ids = ::SmsOptOut.where(user_id: batch.map(&:user_id)).pluck(:user_id).to_set
      batch.each { |predefined_user_parameter| invite(predefined_user_parameter, opted_out_user_ids) }
    end
  end

  def invite(predefined_user_parameter, opted_out_user_ids)
    user = predefined_user_parameter.user
    send_sms_invitation(predefined_user_parameter, user, opted_out_user_ids)
    send_email_invitation(predefined_user_parameter, user)
  rescue ActiveRecord::ActiveRecordError => e
    Sentry.capture_exception(e)
  end

  def send_sms_invitation(predefined_user_parameter, user, opted_out_user_ids)
    return unless predefined_user_parameter.sms_notification && user.phone.present?
    return if ::V1::PredefinedParticipants::SmsDeliverability.refusal(user, opted_out_user_ids: opted_out_user_ids)

    V1::Intervention::PredefinedParticipants::SendSmsInvitation.call(user)
  end

  def send_email_invitation(predefined_user_parameter, user)
    return unless predefined_user_parameter.email_notification && !user.email_autogenerated

    V1::Intervention::PredefinedParticipants::SendEmailInvitation.call(user)
  end

  def predefined_user_parameters
    @predefined_user_parameters ||= intervention.predefined_user_parameters
  end

  def set_autoclose_for_sessions
    intervention.sessions.find_each do |session|
      next unless session.autoclose_enabled

      SessionJobs::AutocloseSessionJob.set(wait_until: session.autoclose_at).perform_later(session.id)
    end
  end
end
